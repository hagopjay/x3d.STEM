"""Render the small Markdown subset x3d.STEM debriefs use into one self-contained HTML page.

  python3 -E -s -m stemkit.docs docs/DEBRIEF.md docs/DEBRIEF.html "Kerr 2 debrief"

Supported: # headings, paragraphs, - and 1. lists, | tables |, ``` fences, **bold**, *italic*, `code`,
[links](url). Everything else is escaped text. No external fonts, scripts or styles.
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

CSS = """body{margin:0;background:#101215;color:#e6e2d8;font:16px/1.6 system-ui,sans-serif}
main{max-width:860px;margin:0 auto;padding:2.5rem 1.4rem 4rem}h1{font-size:28px;line-height:1.25}
h2{font-size:20px;margin-top:2.2rem;border-top:1px solid #2a2e33;padding-top:1.2rem}h3{font-size:17px}
a{color:#e0b96a}code{background:#1d2126;padding:.1em .35em;border-radius:4px;font-size:.92em}
pre{background:#1d2126;padding:1rem;border-radius:8px;overflow:auto}pre code{background:none;padding:0}
table{border-collapse:collapse;margin:1rem 0;font-size:14.5px;width:100%}th,td{border:1px solid #2f343a;padding:.4rem .6rem;vertical-align:top;text-align:left}
th{background:#1a1d21}li{margin:.3rem 0}strong{color:#fff}"""


def inline(s: str) -> str:
    out, i = [], 0
    for m in re.finditer(r"`([^`]+)`", s):
        out.append(_emph(s[i:m.start()]))
        out.append("<code>" + html.escape(m.group(1)) + "</code>")
        i = m.end()
    out.append(_emph(s[i:]))
    return "".join(out)


def _emph(s: str) -> str:
    s = html.escape(s, quote=False)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{html.escape(m.group(2))}">{m.group(1)}</a>', s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    return re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)


def render(md: str, title: str) -> str:
    lines, out, i = md.splitlines(), [], 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("```"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            out.append("<pre><code>" + html.escape("\n".join(lines[i + 1:j])) + "</code></pre>")
            i = j + 1
            continue
        m = re.match(r"(#{1,4}) (.*)", ln)
        if m:
            n = len(m.group(1))
            out.append(f"<h{n}>{inline(m.group(2))}</h{n}>")
            i += 1
            continue
        if ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            head, body = rows[0], rows[1:]
            out.append("<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body) + "</tbody></table>")
            continue
        m = re.match(r"(\s*)(-|\d+\.) (.*)", ln)
        if m:
            tag = "ol" if m.group(2)[0].isdigit() else "ul"
            items = []
            while i < len(lines):
                m = re.match(r"(\s*)(-|\d+\.) (.*)", lines[i])
                if m:
                    items.append(m.group(3))
                elif lines[i].strip() and items and lines[i].startswith("  "):
                    items[-1] += " " + lines[i].strip()
                else:
                    break
                i += 1
            out.append(f"<{tag}>" + "".join(f"<li>{inline(t)}</li>" for t in items) + f"</{tag}>")
            continue
        if not ln.strip():
            i += 1
            continue
        para = [ln]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r"(#{1,4} |\||```|\s*(-|\d+\.) )", lines[i]):
            para.append(lines[i])
            i += 1
        out.append("<p>" + inline(" ".join(p.strip() for p in para)) + "</p>")
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f"<title>{html.escape(title)}</title><style>{CSS}</style></head><body><main>" + "\n".join(out) + "</main></body></html>\n")


def _num(x) -> str:
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        return str(x)
    a = abs(x)
    return f"{x:.3g}" if a and (a < 1e-3 or a >= 1e5) else f"{x:.4g}"


def numbers(paths: list[Path], title: str) -> str:
    """Witness tables generated from case manifests, so debrief numbers are never retyped."""
    out = [f"# {title}", "", "Generated by `stemkit.docs --numbers` from the case manifests; do not edit by hand.", ""]
    for p in paths:
        c = json.loads(Path(p).read_text())
        red = sum(not w["pass"] for w in c["witnesses"])
        out += [f"## {c['id']}" + (f" · {c['title']}" if c.get("title") else ""), "",
                f"Builder `{c['builder_sha256'][:12]}` · {len(c['witnesses'])} witnesses, {red} red.", "",
                "| | Witness | Observed | Rule | Limit |", "|---|---|---|---|---|"]
        for w in c["witnesses"]:
            wid = w["id"].replace("|", "\u2223")       # a pipe would split the table cell
            out.append(f"| {'✓' if w['pass'] else '✗'} | {wid} | {_num(w['observed'])} | {w['rule']} | {_num(w['limit'])} |")
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if sys.argv[1] == "--numbers":
        dst, title, srcs = sys.argv[2], sys.argv[3], sys.argv[4:]
        Path(dst).write_text(numbers([Path(x) for x in srcs], title))
        print(dst)
    else:
        src, dst, title = sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "Debrief"
        Path(dst).write_text(render(Path(src).read_text(), title))
        print(dst)
